"""Downloadable assessment report generation (Markdown / Text / CSV)."""
from __future__ import annotations

import io
from datetime import datetime
import pandas as pd
from genai_explainer import fallback_explanation


def generate_markdown_report(result: dict, sched: dict, explanation: dict | None, lang: str = "en") -> str:
    """Generate a clean, professional, downloadable assessment summary without secrets."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    est = result.get("estimates", {})
    inp = result.get("inputs_used", {})

    lines = [
        "# CaneWater AI — Precision Sugarcane Irrigation Assessment Report",
        f"**Generated:** {now_str} | **Planning Period:** {est.get('planning_period_days', 7)} days",
        "",
        "---",
        "## 1. Field Parameters (Ground Truth)",
        f"- **Crop Age & Growth Stage:** {inp.get('crop_age_months', 'n/a')} months | {inp.get('growth_stage')}",
        f"- **Soil Texture Type & Moisture:** {inp.get('soil_type')} | {inp.get('soil_moisture_pct')}% (Volumetric: {inp.get('moisture_is_volumetric')})",
        f"- **Soil-Water Limits:** FC = {inp.get('field_capacity_pct') or 'n/a'}%, PWP = {inp.get('wilting_point_pct') or 'n/a'}%, Root Depth = {inp.get('root_depth_m') or 'n/a'} m",
        f"- **Weather & Rainfall:** {inp.get('weather')} weather | {inp.get('rainfall_category')} ({inp.get('rainfall_mm') or 0} mm)",
        f"- **Reference ETo:** {inp.get('eto_mm_day') or 'n/a'} mm/day",
        f"- **Irrigation System:** {inp.get('irrigation_method')} | Efficiency = {inp.get('irrigation_efficiency_pct') or 'n/a'}%",
        f"- **Field Area & Water Storage:** {inp.get('area_ha') or 'n/a'} ha | Storage = {inp.get('available_water_m3') or 'n/a'} m³",
        f"- **Pump Discharge Capacity:** {inp.get('pump_flow_m3_per_h') or 'n/a'} m³/h",
        "",
        "## 2. Deterministic Water Balances (FAO-56 Standard)",
        f"- **Crop Evapotranspiration (ETc):** {est.get('etc_mm_day') or 'n/a'} mm/day (Kc = {est.get('kc')})",
        f"- **Crop Water Demand (Period):** {est.get('crop_demand_mm') or 'n/a'} mm",
        f"- **Effective Rainfall Credit (80%):** {est.get('effective_rain_mm') or '0.0'} mm",
        f"- **Net Irrigation Requirement:** {est.get('net_irrigation_mm') or 'n/a'} mm (Basis: {est.get('net_basis')})",
        f"- **Gross Irrigation Requirement:** {est.get('gross_irrigation_mm') or 'n/a'} mm",
        f"- **Net Water Volume Needed:** {est.get('net_volume_m3') or 'n/a'} m³",
        f"- **Gross Water Volume Needed:** {est.get('gross_volume_m3') or 'n/a'} m³",
        "",
        "## 3. Irrigation Schedule Recommendation",
        f"- **Status Code:** {sched.get('status_code')} ({sched.get('status_label')})",
        f"- **Next Action / Review Date:** {sched.get('review_date') or 'Not calculable'} (in {sched.get('review_in_days')} days)",
        f"- **Pump Operating Duration:** {sched.get('irrigation_duration_h') or 'n/a'} hours",
        f"- **Storage Water Sufficiency:** {sched.get('water_sufficient') or 'n/a'} (Coverage: {sched.get('water_coverage_pct') or 'n/a'}%)",
        "- **Scheduling Reasons:**",
    ]
    for r in sched.get("reasons", []):
        lines.append(f"  * {r}")
    lines.append("- **Reassessment Factors:**")
    for f in sched.get("reassess_factors", []):
        lines.append(f"  * {f}")

    lines.extend([
        "",
        "## 4. Multilingual Advisory & Validation Audit",
    ])
    if explanation and explanation.get("text"):
        lines.extend([
            f"- **Advisory Language:** {explanation.get('language')}",
            f"- **Source:** {explanation.get('source').upper()}",
            f"- **Validation Passed:** {explanation.get('source') == 'ai' or explanation.get('fallback_reason') is not None}",
            f"- **Attempts Used:** {explanation.get('attempts', 1)}",
            "",
            "### Advisory Text:",
            explanation["text"],
        ])
    else:
        lines.extend([
            f"- **Advisory Language:** {lang}",
            "- **Source:** DETERMINISTIC FALLBACK",
            "",
            "### Advisory Text:",
            fallback_explanation(result, sched, lang),
        ])

    lines.extend([
        "",
        "## 5. System Limitations & Scientific Assumptions",
    ])
    for a in result.get("assumptions", []):
        lines.append(f"- {a}")
    for lim in result.get("limitations", []):
        lines.append(f"- {lim}")

    lines.extend([
        "",
        "---",
        "## Educational Prototype Disclaimer",
        "This report was generated by CaneWater AI, an educational decision-support prototype. "
        "The figures provided are estimates based on user-supplied inputs and FAO-56 scientific equations. "
        "They do not constitute agronomically certified advice. Verify all irrigation decisions with "
        "direct field observations, soil moisture monitoring, and qualified local agricultural advisers.",
    ])

    return "\n".join(lines)


def generate_schedule_csv(sched: dict) -> str:
    """Generate a CSV string of the irrigation schedule rows."""
    rows = sched.get("rows", [])
    if not rows:
        return "date,action,net_depth_mm,note\n"
    df = pd.DataFrame(rows)
    return df.to_csv(index=False)
